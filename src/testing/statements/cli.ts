/**
 * Write the test statement scenarios to disk for manual testing.
 *
 *   npm run gen:statements                       → samples/statements/
 *   npm run gen:statements -- --out /tmp/stmts
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { buildScenarios, finStatementSource, type Scenario } from './scenarios.js';

export interface WriteResult {
  outDir: string;
  scenarios: { id: string; files: string[] }[];
}

/** Render every scenario into `<outDir>/<scenario id>/…` plus a README describing expectations. */
export async function writeScenarios(outDir: string, scenarios: Scenario[]): Promise<WriteResult> {
  await fs.rm(outDir, { recursive: true, force: true });
  await fs.mkdir(outDir, { recursive: true });
  const result: WriteResult = { outDir, scenarios: [] };
  const readme: string[] = [
    '# FinFolio test statements',
    '',
    'Generated by `npm run gen:statements` from the demo user `fin` (seed date 2026-10-25).',
    'Import them on the Import page to exercise duplicate detection, categorisation and',
    'parsing. Amounts follow the bank convention: negative = money out.',
    '',
    '**Which target account you import into decides what you will see.** S1, S2, S4–S10 are',
    'rendered from transactions `fin` already has, so importing them into `fin` is the',
    '"nothing new, everything already recorded" check — only the planted rows (S3 CATCHUP-*,',
    'S4 PLANT-*, S5 COFFEE-*/REPEAT-*, S6 EUR-*, S7 PENDING-*/FUTURE-1) behave differently.',
    'To see rows being imported, use S3 or S12 into `fin`, or create a fresh user/account',
    '(see docs/IMPORT_TEST_SUITE.md §0.2) and import S1 first.',
    '',
  ];
  for (const sc of scenarios) {
    const dir = path.join(outDir, sc.id);
    await fs.mkdir(dir, { recursive: true });
    const files: string[] = [];
    readme.push(`## ${sc.id} — ${sc.title}`, '', sc.description, '', '| File | Expected |', '|---|---|');
    for (const f of sc.files) {
      await fs.writeFile(path.join(dir, f.name), f.bytes);
      files.push(f.name);
      readme.push(`| \`${f.name}\` | ${f.expect} |`);
    }
    readme.push('');
    result.scenarios.push({ id: sc.id, files });
  }
  await fs.writeFile(path.join(outDir, 'README.md'), readme.join('\n'));
  return result;
}

async function main() {
  const args = process.argv.slice(2);
  const outIdx = args.indexOf('--out');
  const outDir = path.resolve(outIdx !== -1 && args[outIdx + 1] ? args[outIdx + 1] : path.join(process.cwd(), 'samples', 'statements'));
  const src = await finStatementSource();
  const result = await writeScenarios(outDir, buildScenarios(src));
  console.log(`📄 Test statements written to ${result.outDir}`);
  for (const sc of result.scenarios) console.log(`  ${sc.id.padEnd(4)} ${sc.files.length} file(s)`);
  console.log('See README.md in that folder for what each file should do when imported.');
}

const isDirectRun = (() => {
  try { return !!process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href; } catch { return false; }
})();
if (isDirectRun) main().catch(err => { console.error(err); process.exit(1); });
